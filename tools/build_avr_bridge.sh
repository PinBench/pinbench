#!/usr/bin/env bash
# Builds web/avr_bridge.js — the web's ATmega328P — from the same Dart the
# desktop runs (packages/pinbench_sim/lib/core/avr_interop_io.dart), with
# dart2js. The output is committed so `flutter run -d chrome` and the website
# build need no extra step; CI rebuilds it and fails if it drifted.
#
#   tools/build_avr_bridge.sh          rebuild web/avr_bridge.js
#   tools/build_avr_bridge.sh --check  exit 1 if the committed file is stale
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
pkg="$root/packages/pinbench_sim"
out="$root/web/avr_bridge.js"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# Resolved by the app, not by pinbench_sim: the app's pubspec.lock is
# committed and pins avr8_dart, so a new avr8_dart release cannot make --check
# fail on a commit that changed nothing.
(cd "$root" && flutter pub get --enforce-lockfile >/dev/null)
# -O4 is safe here: the bridge does no type tests that -O4's assumptions
# could break, and it is the build the benchmark's 4.4x real time came from.
(cd "$pkg" && dart compile js -O4 --no-source-maps \
  --packages="$root/.dart_tool/package_config.json" \
  -o "$tmp/avr_bridge.js" web_bridge/avr_bridge_main.dart >/dev/null)

{
  echo "// GENERATED by tools/build_avr_bridge.sh from"
  echo "// packages/pinbench_sim/web_bridge/avr_bridge_main.dart — do not edit."
  cat "$tmp/avr_bridge.js"
} > "$tmp/avr_bridge.out.js"

if [[ "${1:-}" == "--check" ]]; then
  if ! cmp -s "$tmp/avr_bridge.out.js" "$out"; then
    echo "web/avr_bridge.js is stale: run tools/build_avr_bridge.sh and commit it." >&2
    exit 1
  fi
  echo "web/avr_bridge.js is up to date."
else
  mv "$tmp/avr_bridge.out.js" "$out"
  echo "Wrote web/avr_bridge.js ($(wc -c < "$out" | tr -d ' ') bytes)."
fi
